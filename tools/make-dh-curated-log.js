#!/usr/bin/env node
'use strict';
/* Writes audit/dh-curated-log.md from the build report (audit/dh-curated-data/_report.json etc.) plus the hand-written sections in
   audit/dh-curated-data/_log-intro.md and _log-outro.md.  Usage: node site/tools/make-dh-curated-log.js */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const DATA = path.join(ROOT, 'audit', 'dh-curated-data');
const rd = (f, d) => { try { return JSON.parse(fs.readFileSync(path.join(DATA, f), 'utf8')); } catch (e) { return d; } };
const txt = f => { try { return fs.readFileSync(path.join(DATA, f), 'utf8'); } catch (e) { return ''; } };
const { report, dropped } = rd('_report.json', { report: [], dropped: [] });
const fstats = rd('_filterstats.json', {});
const jp = rd('_jackpots.json', {});
const total = report.reduce((a, r) => a + r.n, 0);
const bins = [[500, 999], [1000, 1999], [2000, 2999], [3000, 3999], [4000, 5000]];
const hist = bins.map(([a, b]) => [a + '-' + b, report.filter(r => r.n >= a && r.n <= b).length]);
const cats = {}; report.forEach(r => cats[r.cat] = (cats[r.cat] || 0) + 1);
const diffs = { 1: 0, 2: 0, 3: 0 }; report.forEach(r => diffs[r.diff]++);
const ns = report.map(r => r.n).sort((a, b) => a - b);
const median = ns.length ? ns[Math.floor(ns.length / 2)] : 0;
let out = txt('_log-intro.md');
out += `\n## Results (generated by make-dh-curated-log.js)\n\n`;
out += `- Questions: **${report.length}** (${total.toLocaleString('en-US')} accepted answers in total); smallest ${ns[0]}, median ${median}, largest ${ns[ns.length - 1]} answers per question.\n`;
out += `- Difficulty: easy ${diffs[1]}, medium ${diffs[2]}, hard ${diffs[3]}. Jackpots (Dark Horse answers): ${Object.keys(jp).filter(k => report.find(r => r.key === k)).length} questions.\n`;
out += `- Categories: ${Object.entries(cats).sort().map(([k, v]) => k + '=' + v).join(', ')}.\n\n`;
out += `### Answers-per-question histogram\n\n| answers | questions |\n|---|---|\n` + hist.map(h => `| ${h[0]} | ${h[1]} |`).join('\n') + '\n\n';
out += `### Questions, sizes, weight split and sources\n\n| id | key | answers | weights 1/2/3/4/5 | jackpot | type filter (kept of fetched) | prompt |\n|---|---|---|---|---|---|---|\n`;
for (const r of report) out += `| ${r.id} | ${r.key} | ${r.n} | ${r.hist.join('/')} | ${r.jackpot || '-'} | ${fstats[r.key] ? fstats[r.key].out + ' of ' + fstats[r.key].in : '-'} | ${r.prompt} |\n`;
out += `\n### Source listing per question\n\n`;
for (const r of report) out += `- ${r.id} (${r.key}): ${r.src}\n`;
out += `\n### Dropped\n\n` + (dropped.length ? dropped.map(d => `- ${d[0]}: ${d[1]}`).join('\n') : '- none') + '\n';
out += '\n' + txt('_log-outro.md');
fs.writeFileSync(path.join(ROOT, 'audit', 'dh-curated-log.md'), out);
console.log('wrote audit/dh-curated-log.md', out.length, 'chars');
